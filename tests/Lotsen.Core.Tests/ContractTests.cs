using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using Lotsen.Operations;

namespace Lotsen.Tests;

/// <summary>
/// Covers that the UI's contract files are what the C# types and the serializer write: the schema document that <c>ui/src/lib/contract.generated.ts</c> is generated from, and the golden fixtures
/// that the UI tests feed through the UI's own code.
/// </summary>
/// <remarks>The UI's tests check that the generated TypeScript is what the generator writes from the committed schema, and its type check checks the fixtures against that TypeScript.</remarks>
[Trait("Category", "Contract")]
public sealed class ContractTests
{
   /// <summary>The environment variable that, set to <c>1</c>, makes the tests write the files and pass.</summary>
   private const string UpdateVariable = "LOTSEN_UPDATE_CONTRACT";

   private const string SchemaFile = "ui/src/lib/contract.schema.json";
   private const string FixturesFile = "ui/tests/contract/fixtures.generated.ts";

   [Fact]
   public void Schema_is_what_the_types_export() => Check(SchemaFile, Json(ContractDocument.Build(), indent: 2) + "\n");

   [Fact]
   public void Fixtures_are_what_the_serializer_writes() => Check(FixturesFile, Fixtures());

   [Fact]
   public void Every_event_kind_and_every_operation_of_the_ui_has_a_fixture()
   {
      Assert.Equal(ServerEvents.All.Select(kind => kind.Name), ContractSamples.Events().Keys);
      Assert.Equal(UiContract.Operations.Select(operation => operation.Name), ContractSamples.Outputs().Keys);
   }

   private static string Fixtures() => new StringBuilder()
      .Append("// Generated by ContractTests from what the server sends: one event of each kind, and the output of each operation that the UI calls. Do not edit: run `just contract`.\n")
      .Append("import type { EventPayloads, Operations } from '../../src/lib/contract.generated';\n\n")
      .Append("export const eventFixtures = ").Append(Json(new JsonObject(ContractSamples.Events().Select(entry => KeyValuePair.Create(entry.Key, (JsonNode?)entry.Value))), indent: 3))
      .Append(" satisfies EventPayloads;\n\n")
      .Append("export const outputFixtures = ").Append(Json(new JsonObject(ContractSamples.Outputs().Select(entry => KeyValuePair.Create(entry.Key, (JsonNode?)entry.Value))), indent: 3))
      .Append(" satisfies { [N in keyof Operations]: Operations[N]['output'] };\n")
      .ToString();

   private static string Json(JsonNode node, int indent)
   {
      using var stream = new MemoryStream();
      using (var writer = new Utf8JsonWriter(stream, new JsonWriterOptions { Indented = true, IndentSize = indent, NewLine = "\n", Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping }))
      {
         node.WriteTo(writer);
      }

      return Encoding.UTF8.GetString(stream.ToArray());
   }

   private static void Check(string relativePath, string written)
   {
      var path = RepositoryFile.PathOf(relativePath);
      if (Environment.GetEnvironmentVariable(UpdateVariable) == "1")
      {
         Directory.CreateDirectory(Path.GetDirectoryName(path)!);
         File.WriteAllText(path, written);
         return;
      }

      var stored = File.Exists(path) ? File.ReadAllText(path) : "";
      var storedLines = stored.Split('\n');
      var writtenLines = written.Split('\n');
      var first = Enumerable.Range(0, Math.Max(storedLines.Length, writtenLines.Length))
         .FirstOrDefault(line => line >= storedLines.Length || line >= writtenLines.Length || storedLines[line] != writtenLines[line], -1);
      Assert.True(
         first < 0,
         $"{relativePath} differs from what the code writes, first at line {first + 1}. Run `just contract` to write it again.\n"
            + $"  stored:  {storedLines.ElementAtOrDefault(first)}\n  written: {writtenLines.ElementAtOrDefault(first)}");
   }
}
