internal sealed partial class LotsenJsonContext : JsonSerializerContext
{
   /// <summary>Applies lotsen's JSON settings to options that another component created, such as the HTTP options.</summary>
   public static void Configure(JsonSerializerOptions options)
   {
      options.NumberHandling = JsonNumberHandling.Strict;
      options.RespectNullableAnnotations = true;
      options.RespectRequiredConstructorParameters = true;
      options.TypeInfoResolverChain.Insert(0, Default);
   }
}
